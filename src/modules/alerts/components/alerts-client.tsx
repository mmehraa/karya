"use client";

import { useMemo, useState } from "react";
import { AlertCircle, Bell, CircleAlert, Info } from "lucide-react";

import type { SerializedAlert } from "../types";

type AlertFilter = "ALL" | "CRITICAL" | "WARNING" | "INFO";

interface AlertsClientProps {
  alerts: SerializedAlert[];
}

function formatAlertDate(date: Date): string {
  return new Intl.DateTimeFormat("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  }).format(new Date(date));
}

function getSeverityLabel(
  severity: SerializedAlert["severity"],
): string {
  switch (severity) {
    case "CRITICAL":
      return "Critical";
    case "WARNING":
      return "Warning";
    case "INFO":
      return "Info";
    default:
      return severity;
  }
}

function getSeverityStyles(
  severity: SerializedAlert["severity"],
) {
  switch (severity) {
    case "CRITICAL":
      return {
        dot: "bg-red-500",
        pill: "bg-red-50 text-red-600",
      };

    case "WARNING":
      return {
        dot: "bg-amber-500",
        pill: "bg-amber-50 text-amber-700",
      };

    case "INFO":
      return {
        dot: "bg-blue-500",
        pill: "bg-blue-50 text-blue-700",
      };

    default:
      return {
        dot: "bg-slate-400",
        pill: "bg-slate-100 text-slate-600",
      };
  }
}

function getSeverityIcon(
  severity: SerializedAlert["severity"],
) {
  switch (severity) {
    case "CRITICAL":
      return AlertCircle;

    case "WARNING":
      return CircleAlert;

    case "INFO":
      return Info;

    default:
      return Bell;
  }
}

export function AlertsClient({
  alerts,
}: AlertsClientProps) {
  const [filter, setFilter] =
    useState<AlertFilter>("ALL");

  /*
   * Alerts are already tenant-scoped and generated by the
   * alerts service. The UI only filters what is displayed.
   *
   * Resolved alerts are intentionally excluded from the
   * primary Attention Center view.
   */
  const activeAlerts = useMemo(
    () =>
      alerts.filter(
        (alert) => !alert.isResolved,
      ),
    [alerts],
  );

  const filteredAlerts = useMemo(() => {
    if (filter === "ALL") {
      return activeAlerts;
    }

    return activeAlerts.filter(
      (alert) => alert.severity === filter,
    );
  }, [activeAlerts, filter]);

  const filterItems: {
    key: AlertFilter;
    label: string;
  }[] = [
    {
      key: "ALL",
      label: "All",
    },
    {
      key: "CRITICAL",
      label: "Critical",
    },
    {
      key: "WARNING",
      label: "Warning",
    },
    {
      key: "INFO",
      label: "Info",
    },
  ];

  return (
    <section className="overflow-hidden rounded-2xl border border-slate-200 bg-white shadow-sm">
      {/* Header */}
      <div className="border-b border-slate-100 px-6 py-5">
        <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
          <div>
            <h1 className="text-2xl font-bold tracking-tight text-slate-950">
              Alerts
            </h1>

            <p className="mt-1 text-sm text-slate-500">
              Important things that need your attention.
            </p>
          </div>

          {/* Filters */}
          <div className="flex flex-wrap items-center gap-2">
            {filterItems.map((item) => {
              const isActive =
                filter === item.key;

              return (
                <button
                  key={item.key}
                  type="button"
                  onClick={() =>
                    setFilter(item.key)
                  }
                  className={[
                    "rounded-full border px-4 py-2 text-xs font-medium transition-all",
                    isActive
                      ? "border-emerald-900 bg-emerald-900 text-white shadow-sm"
                      : "border-slate-200 bg-white text-slate-600 hover:border-slate-300 hover:bg-slate-50 hover:text-slate-900",
                  ].join(" ")}
                >
                  {item.label}
                </button>
              );
            })}
          </div>
        </div>
      </div>

      {/* Alert List */}
      {filteredAlerts.length > 0 ? (
        <div className="px-6">
          {filteredAlerts.map(
            (alert, index) => {
              const styles =
                getSeverityStyles(
                  alert.severity,
                );

              const SeverityIcon =
                getSeverityIcon(
                  alert.severity,
                );

              const rowContent = (
                <div
                  className={[
                    "flex items-center gap-4 py-4",
                    index !==
                      filteredAlerts.length - 1
                      ? "border-b border-slate-100"
                      : "",
                  ].join(" ")}
                >
                  {/* Severity indicator */}
                  <div className="flex w-5 shrink-0 justify-center">
                    <span
                      className={[
                        "h-2.5 w-2.5 rounded-full",
                        styles.dot,
                      ].join(" ")}
                    />
                  </div>

                  {/* Alert information */}
                  <div className="min-w-0 flex-1">
                    <div className="flex items-start gap-2">
                      <h2 className="truncate text-sm font-semibold text-slate-900">
                        {alert.title}
                      </h2>
                    </div>

                    <p className="mt-0.5 truncate text-xs text-slate-500">
                      {alert.message}
                    </p>
                  </div>

                  {/* Severity */}
                  <div className="hidden shrink-0 sm:block">
                    <span
                      className={[
                        "inline-flex min-w-[100px] items-center justify-center rounded-full px-3 py-1.5 text-xs font-semibold",
                        styles.pill,
                      ].join(" ")}
                    >
                      {getSeverityLabel(
                        alert.severity,
                      )}
                    </span>
                  </div>

                  {/* Date */}
                  <div className="w-[92px] shrink-0 text-right">
                    <p className="text-xs font-medium text-slate-400">
                      {formatAlertDate(
                        alert.createdAt,
                      )}
                    </p>
                  </div>

                  {/* Mobile severity icon */}
                  <div className="flex sm:hidden">
                    <SeverityIcon
                      className="h-4 w-4 text-slate-400"
                    />
                  </div>
                </div>
              );

              if (alert.linkUrl) {
                return (
                  <a
                    key={alert.id}
                    href={alert.linkUrl}
                    className="block transition-colors hover:bg-slate-50/70"
                  >
                    {rowContent}
                  </a>
                );
              }

              return (
                <div key={alert.id}>
                  {rowContent}
                </div>
              );
            },
          )}
        </div>
      ) : (
        <div className="flex min-h-[300px] flex-col items-center justify-center px-6 py-12 text-center">
          <div className="flex h-12 w-12 items-center justify-center rounded-full bg-slate-50">
            <Bell className="h-5 w-5 text-slate-400" />
          </div>

          <h2 className="mt-4 text-sm font-semibold text-slate-900">
            {filter === "ALL"
              ? "No active alerts"
              : `No ${getSeverityLabel(
                  filter,
                ).toLowerCase()} alerts`}
          </h2>

          <p className="mt-1 max-w-sm text-xs leading-5 text-slate-500">
            {filter === "ALL"
              ? "Nothing currently requires your attention."
              : "There are no active alerts in this severity category."}
          </p>
        </div>
      )}
    </section>
  );
}